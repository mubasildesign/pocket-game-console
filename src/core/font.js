export function textWidth(str, scale = 1) {
  let w = 0;
  const s = String(str).toUpperCase();
  for (let i = 0; i < s.length; i++) w += (s[i] === ' ' ? 4 : 6) * scale;
  return w;
}

export function drawText(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  let cx = x;
  const s = String(str).toUpperCase();
  for (const ch of s) {
    if (ch === ' ') {
      cx += 4 * scale;
      continue;
    }
    const rows = FONT[ch];
    if (!rows) {
      cx += 6 * scale;
      continue;
    }
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (rows[r] & (1 << (4 - c))) {
          ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale;
  }
  return cx;
}
