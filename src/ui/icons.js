export function drawIcon(gfx, id, x, y, color, size = 4) {
  const rows = ICONS[id];
  if (!rows) return;
  rows.forEach((row, ry) => {
    for (let rx = 0; rx < row.length; rx++) {
      if (row[rx] === '#') gfx.rect(x + rx * size, y + ry * size, size - 1, size - 1, color);
    }
  });
}
